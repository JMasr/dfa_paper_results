"""Build table views; retain source values with explicit p-value formatting."""
from pathlib import Path
import re
import argparse
parser=argparse.ArgumentParser();parser.add_argument("--root",type=Path,default=Path(__file__).resolve().parents[1]/"outputs");args=parser.parse_args()
ROOT = Path(__file__).resolve().parents[1]
OUT = args.root / 'layout'
OUT.mkdir(exist_ok=True)
source = (args.root / 'generated/sota_tab_regime.tex').read_text()
view = source.replace('\\begin{tabular}{llcccc}', '\\begin{tabular}{>{\\raggedright\\arraybackslash}p{0.26\\linewidth}lcccc}')
view = view.replace('%% GENERATED by tools/build_paper_sota.py -- DO NOT EDIT BY HAND.', '%% Presentation view of generated/sota_tab_regime.tex; numeric cells unchanged.')
(OUT / 'tab_material.tex').write_text(view)
source = (args.root / 'generated/sota_tab_contrasts.tex').read_text()
view = source.replace('Supplementary Table~S9', 'Supplementary Table~\\suppref{tab:supps_stats}')
view = view.replace('%% GENERATED by tools/build_paper_sota.py -- DO NOT EDIT BY HAND.', '%% Presentation view of generated/sota_tab_contrasts.tex; numeric cells unchanged.')
(OUT / 'tab_contrasts.tex').write_text(view)
source = (args.root / 'generated/supps_tab_stats.tex').read_text()
caption = re.search(r'\\caption\{(.*?)\}\n\\label', source, re.S).group(1)
caption = caption.replace(
    'n/a when fewer than six non-zero blocks make a test impossible',
    'n/a under the reporting rule for fewer than six non-zero blocks',
)
caption += r' Values of $p$ rounded to 0.000 are displayed as $<0.001$.'
entries = []
for line in source.splitlines():
    if '\\multicolumn{12}' in line:
        entries.append(('group', line))
    elif line.startswith('\\quad '):
        cells = [c.strip() for c in line.split('&')]
        assert len(cells) == 12
        cells[-1] = cells[-1].rsplit('\\\\', 1)[0].strip()
        entries.append(('row', cells))
header = r'Contrast & Stage & $\Delta$ & $p$ & $q$ & Blocks & MDE \\' + '\n'
view = '''%% Presentation view of generated/supps_tab_stats.tex.
%% Source values retained; p rounded to 0.000 displayed as <0.001.
%% Endpoints are stacked for readability.
\\begingroup
\\footnotesize
\\setlength{\\tabcolsep}{3pt}
\\setlength{\\LTleft}{0pt}
\\setlength{\\LTright}{0pt}
\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{0.34\\linewidth}crrrcr@{}}
'''
view += '\\caption{' + caption + '}\\label{tab:supps_stats}\\\\\n\\toprule\n' + header + '\\midrule\n\\endfirsthead\n'
view += '\\caption[]{Full statistics of paired contrasts (continued).}\\\\\n\\toprule\n' + header + '\\midrule\n\\endhead\n'
view += '\\midrule\\multicolumn{7}{r}{Continued on next page}\\\\\n\\endfoot\n\\bottomrule\n\\endlastfoot\n'
for endpoint, start in [('AUROC', 2), ('macro-F1', 7)]:
    view += '\\addlinespace[3pt]\\multicolumn{7}{l}{\\textbf{' + endpoint + '}}\\\\[2pt]\n'
    for kind, value in entries:
        if kind == 'group':
            # Let long family headings wrap rather than shrink every numeric column.
            group = value.replace('\\multicolumn{12}{l}', '\\multicolumn{7}{p{0.94\\linewidth}}')
            view += group + '\n'
        else:
            displayed = value[:2] + value[start:start + 5]
            if displayed[3] == '0.000':
                displayed[3] = r'$<0.001$'
            view += ' & '.join(displayed) + ' \\\\\n'
view += '\\end{longtable}\n\\endgroup\n'
(OUT / 'tab_stats.tex').write_text(view)
# The two endpoint views must reconstruct each original twelve-column record exactly.
rows = [v for k, v in entries if k == 'row']
rendered = []
for line in view.splitlines():
    if line.startswith('\\quad '):
        cells = [c.strip() for c in line.split('&')]
        cells[-1] = cells[-1].rsplit('\\\\', 1)[0].strip()
        assert len(cells) == 7
        # Reverse only the declared display transform before checking fidelity.
        if cells[3] == r'$<0.001$':
            cells[3] = '0.000'
        rendered.append(cells)
n = len(rows)
assert len(rendered) == 2 * n
for i, original in enumerate(rows):
    assert rendered[i][:2] == rendered[n + i][:2] == original[:2]
    assert rendered[i] + rendered[n + i][2:] == original
print(f'Validated source values in {n} contrasts; p-zero display formatting only.')
